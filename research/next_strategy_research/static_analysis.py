"""Static score/information/allocation analysis. RESEARCH ONLY.

NO episodes are run, NO outcomes are generated by evaluate.py, NO frozen file is
modified. Worlds are created with kit.generate (read-only data generation) and all
quantities are decision-problem statistics computed offline:

  - current greedy score (kit.baseline_match formula: count of observed-equal SOFT)
  - analytic expected-MSMI score using the PUBLISHED outcome structure of kit._prob
    (structure-informed, mirrors research/features.py disclosed practice)
  - oracle score (truth soft fields + hidden per-actor params) -- an UPPER BOUND
    only; a deployed policy may NOT read hidden state.
  - allocations: plain greedy vs maximum-weight matching (networkx blossom),
    at identical scores, on full pools and on subsampled pools of realistic size.

Evidence labels used in the report: [MEASURED-OFFLINE] for everything produced here.
"""
import sys, json, math, itertools, random, statistics, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
import kit  # noqa: E402  (read-only import)
import networkx as nx  # noqa: E402
from scipy.stats import spearmanr  # noqa: E402

VARIANTS = ('development', 'sparse', 'cold_start', 'delayed', 'shift', 'drift')
SEEDS = list(range(107, 119))
W_DEF = {'relationship_goal': .7, 'relationship_pace': .4, 'lifestyle': .25, 'conversations': .2}
W_SHIFT = {'relationship_goal': .25, 'relationship_pace': .8, 'lifestyle': -.25, 'conversations': .5}
REL = tuple(W_DEF)                      # outcome-relevant soft fields (kit._prob)
PRIOR_EQ = {k: 1.0 / len(v) for k, v in kit.OPTIONS.items()}   # P(equal) under uniform prior
RESP_PRIOR = (0.55 + 0.98) / 2.0        # prior mean of hidden response_rate
DATE_HAPPEN = 0.78                      # kit.py:171
EPS = 1e-6                              # card-first tie-break for MWM


def sig(z):
    return 1.0 / (1.0 + math.exp(-max(-60.0, min(60.0, z))))


def weights_for(variant):
    return W_SHIFT if variant == 'shift' else W_DEF


# ---------------------------------------------------------------- pair scores
def s_count(soft_a, soft_b):
    """kit.baseline_match score: count of observed-equal SOFT fields (kit.py:217)."""
    return sum(soft_a.get(k) is not None and soft_a.get(k) == soft_b.get(k)
               for k in kit.SOFT)


def s_analytic(soft_a, soft_b, W):
    """Structure-informed expected-fit score on CURRENTLY observed fields.
    Missing fields contribute their prior expectation w*(1.5*P(eq)-0.5) (neutral
    Bayesian update). Uses only published kit structure + observed values."""
    total = 0.0
    for k, w in W.items():
        va, vb = soft_a.get(k), soft_b.get(k)
        if va is None or vb is None:
            total += w * (1.5 * PRIOR_EQ[k] - 0.5)
        else:
            total += w * (1.0 if va == vb else -0.5)
    # second-meeting stage: relationship_goal equality (kit.py:179), prior if missing
    ga, gb = soft_a.get('relationship_goal'), soft_b.get('relationship_goal')
    goal_eq = PRIOR_EQ['relationship_goal'] if (ga is None or gb is None) else float(ga == gb)
    return total + 0.02 * (1.5 * goal_eq - 0.5)   # small weight for stage-3 term


def pair_value(soft_a, soft_b, W, params_a, params_b):
    """Expected-MSMI proxy for a pair given soft-value dicts and actor params.
    value = P(both respond+accept) * P(date) * P(both respond+second-yes).
    shared ~ N(0,.45) integrated at its mean 0; drift at 0 (rank-preserving);
    date-within-30 ignored (variant/day constant at snapshot)."""
    bias_a, rr_a, sb_a = params_a
    bias_b, rr_b, sb_b = params_b
    fit = 0.0
    for k, w in W.items():
        va, vb = soft_a.get(k), soft_b.get(k)
        if va is None or vb is None:
            fit += w * (1.5 * PRIOR_EQ[k] - 0.5)
        else:
            fit += w * (1.0 if va == vb else -0.5)
    p1 = sig(-0.25 + fit)
    ga, gb = soft_a.get('relationship_goal'), soft_b.get('relationship_goal')
    if ga is None or gb is None:
        geq = PRIOR_EQ['relationship_goal']
        p2a = sig(0.15 + sb_a + 0.4 * geq)
        p2b = sig(0.15 + sb_b + 0.4 * geq)
    else:
        eq = float(ga == gb)
        p2a = sig(0.15 + sb_a + 0.4 * eq)
        p2b = sig(0.15 + sb_b + 0.4 * eq)
    p1a, p1b = sig(-0.25 + bias_a + fit), sig(-0.25 + bias_b + fit)
    return (rr_a * p1a) * (rr_b * p1b) * DATE_HAPPEN * (rr_a * p2a) * (rr_b * p2b)


# ---------------------------------------------------------------- allocations
def greedy_alloc(score_of):
    """kit.py:220-221 exact algorithm: sort (-score, key), take-while-both-free."""
    ordered = sorted(((-s, tuple(sorted(k))) for k, s in score_of.items()))
    used, out = set(), []
    for _, pair in ordered:
        if not used.intersection(pair):
            out.append(pair)
            used.update(pair)
    return out


def mwm_alloc(score_of, nodes):
    """Maximum-weight matching on the general graph (blossom), epsilon-cardinality
    tie-break so free positive edges are always preferred."""
    G = nx.Graph()
    G.add_nodes_from(nodes)
    for (a, b), s in score_of.items():
        G.add_edge(a, b, weight=s + EPS)
    return [tuple(sorted(e)) for e in nx.max_weight_matching(G, maxcardinality=False)]


def alloc_value(pairs, value_of):
    v = [value_of[p] for p in pairs]
    return {'n': len(pairs), 'sum': sum(v), 'mean': (sum(v) / len(v) if v else 0.0)}


# ---------------------------------------------------------------- world driver
def analyse_world(world):
    variant = world['variant']
    W = weights_for(variant)
    members = world['members']
    # matchable = no declined HARD field (after greedy hard-ask saturation every
    # other member has all hard fields observed = truth; kit.py:127 + audit share=1.0)
    matchable = [m for m in members
                 if not any(m['field_status'][k] == 'declined' for k in kit.HARD)]
    views = []
    for m in matchable:
        soft_obs = {k: m['fields'].get(k) for k in kit.SOFT}
        soft_truth = {k: (m['truth'][k] if m['field_status'][k] != 'declined'
                          else m['fields'].get(k)) for k in kit.SOFT}
        soft_rel_only = dict(soft_obs)
        for k in REL:
            if m['field_status'][k] != 'declined':
                soft_rel_only[k] = m['truth'][k]
        view = {'member_id': m['member_id'], 'pool_id': m['pool_id'], 'age': m['age'],
                'gender': m['gender'], 'zone': m['zone'],
                'fields': {**{k: m['truth'][k] for k in kit.HARD}, **soft_obs},
                '_soft_obs': soft_obs, '_soft_truth': soft_truth,
                '_soft_rel': soft_rel_only,
                '_params_true': (m['bias'], m['response_rate'], m['second_bias'])}
        views.append(view)

    # feasible edge set on saturated-hard state
    edges = []
    for a, b in itertools.combinations(views, 2):
        if kit.eligibility(a, b)['status'] != 'feasible':
            continue
        ka, kb = a['member_id'], b['member_id']
        key = (ka, kb) if ka < kb else (kb, ka)
        s_g = s_count(a['_soft_obs'], b['_soft_obs'])
        s_an = s_analytic(a['_soft_obs'], b['_soft_obs'], W_DEF)
        s_rel = s_count(a['_soft_rel'], b['_soft_rel'])
        s_an_rel = s_analytic(a['_soft_rel'], b['_soft_rel'], W_DEF)
        s_full = s_count(a['_soft_truth'], b['_soft_truth'])
        s_orc = s_analytic(a['_soft_truth'], b['_soft_truth'], W_DEF)
        v_oracle = pair_value(a['_soft_truth'], b['_soft_truth'], W,
                              a['_params_true'], b['_params_true'])
        v_softfull = pair_value(a['_soft_truth'], b['_soft_truth'], W,
                                (0.0, RESP_PRIOR, 0.0), (0.0, RESP_PRIOR, 0.0))
        v_obs = pair_value(a['_soft_obs'], b['_soft_obs'], W,
                           (0.0, RESP_PRIOR, 0.0), (0.0, RESP_PRIOR, 0.0))
        edges.append({'k': key, 's_greedy': s_g, 's_analytic': s_an, 's_revealed_rel': s_rel,
                      's_analytic_revealed': s_an_rel,
                      's_revealed7': s_full, 's_oracle': s_orc,
                      'v_oracle': v_oracle, 'v_softfull': v_softfull, 'v_obs': v_obs})

    score_keys = ('s_greedy', 's_analytic', 's_revealed_rel', 's_analytic_revealed',
                  's_revealed7', 's_oracle')
    value_of = {e['k']: e['v_oracle'] for e in edges}
    value_softfull_of = {e['k']: e['v_softfull'] for e in edges}
    nodes = [v['member_id'] for v in views]
    sc = {key: {e['k']: e[key] for e in edges} for key in score_keys}

    # --- validation: my greedy replica must equal kit.baseline_match on this state
    state_members = []
    for v in views:
        mv = {k: v[k] for k in ('member_id', 'pool_id', 'age', 'gender', 'zone', 'fields')}
        mv['available'] = True
        state_members.append(mv)
    kit_state = {'members': state_members, 'introductions': []}
    kit_greedy = [tuple(p) for p in kit.baseline_match(kit_state)]
    my_greedy = greedy_alloc(sc['s_greedy'])
    replica_ok = sorted(kit_greedy) == sorted(my_greedy)

    # --- full-pool allocations
    full = {}
    for key in score_keys:
        full['greedy_' + key] = alloc_value(greedy_alloc(sc[key]), value_of)
    full['mwm_s_greedy'] = alloc_value(mwm_alloc(sc['s_greedy'], nodes), value_of)
    full['mwm_s_oracle'] = alloc_value(mwm_alloc(sc['s_oracle'], nodes), value_of)
    full['mwm_s_analytic_revealed'] = alloc_value(
        mwm_alloc(sc['s_analytic_revealed'], nodes), value_of)

    # --- subsampled pools of realistic daily sizes (busy/past proxy)
    subs = {}
    for size in (25, 60):
        for draw in range(2):
            rng = random.Random(world['seed'] * 10007 + size * 13 + draw * 7 + sum(map(ord, variant)))
            sub_nodes = set(rng.sample(nodes, min(size, len(nodes))))
            for key in ('s_greedy', 's_analytic', 's_revealed_rel', 's_analytic_revealed',
                        's_oracle'):
                sub_sc = {k: s for k, s in sc[key].items()
                          if k[0] in sub_nodes and k[1] in sub_nodes}
                if not sub_sc:
                    continue
                subs.setdefault(f'{size}_{draw}', {})[f'greedy_{key}'] = \
                    alloc_value(greedy_alloc(sub_sc), value_of)
            sub_sc_g = {k: s for k, s in sc['s_greedy'].items()
                        if k[0] in sub_nodes and k[1] in sub_nodes}
            sub_sc_o = {k: s for k, s in sc['s_oracle'].items()
                        if k[0] in sub_nodes and k[1] in sub_nodes}
            if sub_sc_g:
                subs[f'{size}_{draw}']['mwm_s_greedy'] = alloc_value(
                    mwm_alloc(sub_sc_g, list(sub_nodes)), value_of)
                subs[f'{size}_{draw}']['mwm_s_oracle'] = alloc_value(
                    mwm_alloc(sub_sc_o, list(sub_nodes)), value_of)

    # --- rank correlations (info gap) on edges
    corr = {}
    for key in ('s_analytic', 's_revealed_rel', 's_analytic_revealed', 's_revealed7', 's_oracle'):
        if len(edges) >= 3:
            rho = spearmanr([e[key] for e in edges], [e['v_oracle'] for e in edges]).statistic
            corr[key] = float(rho) if rho == rho else None
    # current score vs oracle value
    rho_g = spearmanr([e['s_greedy'] for e in edges],
                      [e['v_oracle'] for e in edges]).statistic
    corr['s_greedy'] = float(rho_g) if rho_g == rho_g else None

    # --- winner flip analysis (argmax under each score, oracle value of winner)
    def winner_value(key):
        best = max(edges, key=lambda e: (e[key], e['k']))
        return best['v_oracle']
    winners = {key: winner_value(key) for key in score_keys}

    # --- ask accounting: reveals needed to fully reveal REL / all7 soft
    rel_asks = sum(1 for m in matchable for k in REL
                   if m['field_status'][k] == 'not_asked')
    all7_asks = sum(1 for m in matchable for k in kit.SOFT
                    if m['field_status'][k] == 'not_asked')
    rel_declined = sum(1 for m in matchable for k in REL
                       if m['field_status'][k] == 'declined')

    return {'seed': world['seed'], 'variant': variant,
            'n_members': len(members), 'n_matchable': len(matchable),
            'n_edges': len(edges), 'replica_ok': replica_ok,
            'full': full, 'subs': subs, 'corr': corr, 'winners': winners,
            'asks_rel': rel_asks, 'asks_all7': all7_asks,
            'rel_declined_unaskable': rel_declined}


def agg(rows):
    """Aggregate per-world metric dicts into mean/median/W-T-L over worlds."""
    out = {}
    # collect all allocation names
    names = set()
    for r in rows:
        names.update(r['full'].keys())
    base = 'greedy_s_greedy'
    for name in sorted(names):
        if name == base:
            continue
        deltas, wins, ties, losses = [], 0, 0, 0
        for r in rows:
            b = r['full'][base]['sum']
            t = r['full'].get(name, {}).get('sum')
            if t is None:
                continue
            d = t - b
            deltas.append(d)
            wins += d > 1e-15; ties += abs(d) <= 1e-15; losses += d < -1e-15
        if deltas:
            out[name] = {'mean_delta_sum_v': statistics.fmean(deltas),
                         'median_delta_sum_v': statistics.median(deltas),
                         'w_t_l': [wins, ties, losses],
                         'mean_base': statistics.fmean(
                             [r['full'][base]['sum'] for r in rows]),
                         'mean_treat': statistics.fmean(
                             [r['full'][name]['sum'] for r in rows if name in r['full']]),
                         'mean_n_base': statistics.fmean(
                             [r['full'][base]['n'] for r in rows]),
                         'mean_n_treat': statistics.fmean(
                             [r['full'][name]['n'] for r in rows if name in r['full']])}
    # subsample aggregates: greedy vs mwm at same score
    sub_agg = {}
    for size in ('25', '60'):
        for cmp_name in ('mwm_s_greedy', 'mwm_s_oracle'):
            deltas = []
            for r in rows:
                for draw_key, d in r['subs'].items():
                    if not draw_key.startswith(size + '_'):
                        continue
                    if 'greedy_' + cmp_name.split('_', 1)[1] in d and cmp_name in d:
                        deltas.append(d[cmp_name]['sum'] -
                                      d['greedy_' + cmp_name.split('_', 1)[1]]['sum'])
            if deltas:
                sub_agg[f'{size}:{cmp_name}'] = {
                    'mean_delta_sum_v': statistics.fmean(deltas),
                    'median_delta_sum_v': statistics.median(deltas),
                    'w_t_l': [sum(d > 1e-15 for d in deltas),
                              sum(abs(d) <= 1e-15 for d in deltas),
                              sum(d < -1e-15 for d in deltas)],
                    'n': len(deltas)}
        # analytic/reveal greedy vs greedy at subsample scale
        for cmp_key in ('greedy_s_analytic', 'greedy_s_revealed_rel',
                        'greedy_s_analytic_revealed', 'greedy_s_oracle'):
            deltas = []
            for r in rows:
                for draw_key, d in r['subs'].items():
                    if not draw_key.startswith(size + '_'):
                        continue
                    if 'greedy_s_greedy' in d and cmp_key in d:
                        deltas.append(d[cmp_key]['sum'] - d['greedy_s_greedy']['sum'])
            if deltas:
                sub_agg[f'{size}:{cmp_key}'] = {
                    'mean_delta_sum_v': statistics.fmean(deltas),
                    'median_delta_sum_v': statistics.median(deltas),
                    'w_t_l': [sum(d > 1e-15 for d in deltas),
                              sum(abs(d) <= 1e-15 for d in deltas),
                              sum(d < -1e-15 for d in deltas)],
                    'n': len(deltas)}
    corr_agg = {}
    for key in ('s_greedy', 's_analytic', 's_revealed_rel', 's_revealed7', 's_oracle'):
        vals = [r['corr'][key] for r in rows if r['corr'].get(key) is not None]
        if vals:
            corr_agg[key] = {'mean': statistics.fmean(vals), 'median': statistics.median(vals)}
    win_agg = {}
    for key in ('s_greedy', 's_analytic', 's_revealed_rel', 's_analytic_revealed',
                's_revealed7', 's_oracle'):
        vals = [r['winners'][key] for r in rows]
        win_agg[key] = {'mean_v_of_winner': statistics.fmean(vals)}
    asks_agg = {'rel_mean_per_world': statistics.fmean([r['asks_rel'] for r in rows]),
                'all7_mean_per_world': statistics.fmean([r['asks_all7'] for r in rows]),
                'rel_declined_mean': statistics.fmean([r['rel_declined_unaskable'] for r in rows])}
    struct = {'n_matchable_mean': statistics.fmean([r['n_matchable'] for r in rows]),
              'n_edges_mean': statistics.fmean([r['n_edges'] for r in rows]),
              'n_edges_median': statistics.median([r['n_edges'] for r in rows]),
              'replica_all_ok': all(r['replica_ok'] for r in rows)}
    return {'full_pool': out, 'subsampled': sub_agg, 'spearman_vs_v_oracle': corr_agg,
            'winner_value': win_agg, 'asks': asks_agg, 'structure': struct}


def main():
    t0 = time.time()
    rows = []
    for variant in VARIANTS:
        for seed in SEEDS:
            world = kit.generate(seed, 200, 'evaluation', variant)
            rows.append(analyse_world(world))
    summary = agg(rows)
    # per-variant breakdown for the key comparison (greedy vs analytic vs revealed)
    per_variant = {}
    for variant in VARIANTS:
        vr = [r for r in rows if r['variant'] == variant]
        per_variant[variant] = {
            key: statistics.fmean([r['full'][key]['sum'] - r['full']['greedy_s_greedy']['sum']
                                   for r in vr])
            for key in ('greedy_s_analytic', 'greedy_s_revealed_rel',
                        'greedy_s_analytic_revealed', 'greedy_s_revealed7',
                        'greedy_s_oracle', 'mwm_s_greedy', 'mwm_s_analytic_revealed')
            if all(key in r['full'] for r in vr)}
    result = {'meta': {'n_worlds': len(rows), 'seeds': [min(SEEDS), max(SEEDS)],
                       'variants': list(VARIANTS),
                       'note': 'offline static analysis; no episodes run; '
                               'shared=0, drift=0 integration; date-window ignored',
                       'elapsed_s': round(time.time() - t0, 1)},
              'summary': summary, 'per_variant_delta_vs_greedy': per_variant,
              'per_world': rows}
    out = Path(__file__).parent / 'static_analysis.json'
    out.write_text(json.dumps(result, indent=1))
    print('wrote', out, 'elapsed', result['meta']['elapsed_s'], 's')
    print(json.dumps({'summary': summary, 'per_variant': per_variant}, indent=1))


if __name__ == '__main__':
    main()
